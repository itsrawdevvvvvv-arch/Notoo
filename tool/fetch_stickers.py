BASE_DOODLE = "https://opendoodles.s3-us-west-1.amazonaws.com/"
BASE_EMOJI = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@latest/assets/72x72/"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOODLE_DIR = os.path.join(ROOT, "assets", "stickers", "doodles")
EMOJI_DIR = os.path.join(ROOT, "assets", "stickers", "emoji")
MANIFEST = os.path.join(ROOT, "lib", "generated", "sticker_manifest.dart")


def download(url: str, dest: str) -> None:
    req = urllib.request.Request(url, headers={"User-Agent": "notoo-ci"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        data = resp.read()
    with open(dest, "wb") as f:
        f.write(data)


def fetch(items, base, out_dir, suffix):
    os.makedirs(out_dir, exist_ok=True)
    got = []
    for key, name in items:
        dest = os.path.join(out_dir, f"{key}{suffix}")
        try:
            download(base + f"{key}{suffix}", dest)
            if os.path.getsize(dest) > 400:
                got.append((name, key))
            else:
                os.remove(dest)
        except Exception as exc:  # noqa: BLE001
            print("FAIL", key, exc)
    return got


def dart_list(name: str, entries, prefix: str) -> str:
    lines = [f"const List<Map<String, String>> {name} = ["]
    for label, key in entries:
        lines.append(
            f"  {{'name': '{label}', 'asset': '{prefix}{key}.png'}},"
        )
    lines.append("];")
    return "\n".join(lines)


def main() -> None:
    doodles = fetch([(d, d.replace('-', ' ').title()) for d in DOODLES],
                    BASE_DOODLE, DOODLE_DIR, ".png")
    emoji = fetch(EMOJI, BASE_EMOJI, EMOJI_DIR, ".png")

    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    body = (
        "// GENERATED by tool/fetch_stickers.py - do not edit by hand.\n"
        "// Open Doodles are CC0; Twemoji graphics are CC-BY 4.0.\n\n"
        + dart_list("kDoodleStickers", doodles, "assets/stickers/doodles/")
        + "\n\n"
        + dart_list("kEmojiStickers", emoji, "assets/stickers/emoji/")
        + "\n"
    )
    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"doodles={len(doodles)} emoji={len(emoji)}")


if __name__ == "__main__":
    main()
