    ("1f60e", "Cool"), ("1f914", "Think"), ("1f644", "Roll eyes"),
    ("1f970", "Smiling hearts"), ("1f973", "Party face"), ("1f929", "Star struck"),
    ("1f4aa", "Flex"), ("1f44d", "Thumbs up"), ("1f44f", "Clap"),
    ("1f64c", "Raise hands"), ("1f64f", "Thanks"), ("1f91d", "Handshake"),
    ("2764", "Heart"), ("1f9e1", "Orange heart"), ("1f499", "Blue heart"),
    ("1f49a", "Green heart"), ("1f49c", "Purple heart"), ("1f5a4", "Black heart"),
    ("1f389", "Party"), ("1f38a", "Confetti"), ("2728", "Sparkles"),
