#!/usr/bin/env python3
"""Download the openly-licensed sticker art Notoo bundles, and write a Dart
manifest listing what was fetched.

Sources:
  * Open Doodles  - CC0 (public domain), no attribution required.
  * Twemoji       - graphics CC-BY 4.0 (attribution shown in Notoo's Settings).

Runs in CI before `flutter pub get`. Any sticker that fails to download is
skipped, so a network hiccup never breaks the build.
"""
