#!/usr/bin/env python3
"""Download the open-licensed (OFL) fonts Notoo bundles, and register the
ones that downloaded in pubspec.yaml.

Runs in CI before `flutter pub get`. Nothing is committed; the fonts are
fetched fresh each build. If a font fails to download it is simply skipped,
so the build never breaks over a network hiccup.
"""
