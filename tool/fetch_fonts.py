    ("Quicksand", "ofl/quicksand/Quicksand%5Bwght%5D.ttf"),
    ("Rubik", "ofl/rubik/Rubik%5Bwght%5D.ttf"),
    ("Work Sans", "ofl/worksans/WorkSans%5Bwght%5D.ttf"),
