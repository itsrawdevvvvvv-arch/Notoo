    ("Roboto Mono", "ofl/robotomono/RobotoMono%5Bwght%5D.ttf"),
    ("IBM Plex Mono", "ofl/ibmplexmono/IBMPlexMono-Regular.ttf"),
    ("Cormorant Garamond", "ofl/cormorantgaramond/CormorantGaramond%5Bwght%5D.ttf"),
